export interface MaterialPromptOptions {
  grade?: string;
  textbook?: string;
  tags?: string[];
}

/**
 * 外部LLM（Gemini 1.5 Pro/Flash, ChatGPT, Claude等）に教材PDF（スキャン画像含む）を読み込ませ、
 * 教材の「大問」や「単元セクション（Lesson 5-1単語など）」ごとにスッキリまとまった
 * 枝問形式（(1), (2), (3)...）のMini-JSONコードブロックを出力させるプロンプトを生成する。
 */
export function buildMaterialExtractionPrompt(options: MaterialPromptOptions = {}): string {
  const { grade, textbook, tags } = options;

  const sampleTb = textbook?.trim() || "中学英語";
  const sampleGr = grade?.trim() || "中1";
  const sampleTags = tags && tags.length > 0 ? tags : ["定期テスト", "単元まとめ"];

  return `あなたは教材の画像解析とデジタルデータ構造化に特化したエキスパートAIです。
添付された教材（PDF・画像）の視覚レイアウトを読み取り、掲載されている【すべての問題・単語・重要表現】を漏れなく抽出し、指定のMini-JSON形式コードブロックのみで出力してください。

※「テキストベースAIだから画像・PDFは処理できない」「一度に抽出できない」といった免責や言い訳、会話文は固く禁止します。
※長大な教材（3ページ以上）の場合は、出力トークン上限による打ち切りを防ぐため、一度に渡されたページ（推奨: 見開き1〜2ページ）の全設問を完全に網羅してください。

---

### 【抽出ルール（最重要：大問・セクションごとの枝問まとめ）】

1. **大問・単元セクションごとに1つのJSONオブジェクトにまとめること（最重要）**:
   - 1問ずつ細切れにバラバラのJSONにするのではなく、教材の【大問】【単元セクション】ごとに1つのJSONオブジェクトにまとめ、その中の小問や単語群は \`(1)\`, \`(2)\`, \`(3)\`... の枝問形式で問題文(q)と解答(a)に改行区切りで記述してください。
   - 【単語まとめのまとめ方例】
     \`Lesson 5-1 単語・重要表現\` のようにセクションごとに1つの大問とし、小問(1)〜(12)として記述します。
     \`\`\`json
     {
       "tb": "${sampleTb}",
       "gr": "${sampleGr}",
       "g": "英語",
       "t": "Lesson 5 単語・重要表現のまとめ",
       "st": "Lesson 5-1 単語まとめ",
       "tg": ["単語"],
       "d": 1,
       "s": 120,
       "q": "次の日本語に合う英語、または英語に合う日本語を書きなさい。\\n(1) 場所、所\\n(2) tourist（意味を答えよ）\\n(3) 彼［彼女、それ］らは［が］\\n(4) 彼（女）らの\\n(5) 身につけている",
       "a": "(1) place\\n(2) 観光客、旅行者\\n(3) they\\n(4) their\\n(5) wear",
       "al": ["(1)", "(2)", "(3)", "(4)", "(5)"],
       "ly": "same-line"
     }
     \`\`\`

2. **教材内の表・リスト形式（「単語・重要表現のまとめ」「重要語句チェック」等）を絶対にスキップしないこと**:
   - ページ上部や見出し下にある単語表や語句チェックも、上記のようにセクションごとに1つの大問（小問リスト）として必ず漏れなく抽出してください。

3. **大問内の小問（適語補充・並べ替え・選択等）のまとめ方**:
   - 大問1、大問2などの練習問題も、各大問を1つのJSONオブジェクトとし、小問(1)〜(n)を問題文(q)と解答(a)にまとめます。
   - 【大問まとめ例（並べ替え）】
     \`\`\`json
     {
       "tb": "${sampleTb}",
       "gr": "${sampleGr}",
       "g": "英語",
       "t": "Lesson 5 文法のまとめ",
       "st": "練習問題 3 並べ替え",
       "tg": ["並べ替え"],
       "d": 2,
       "s": 180,
       "q": "次の日本文の意味を表すように、( )内の語(句)を並べかえなさい。\\n(1) ルーシーは家で英語を話します。( at / English / home / speaks / Lucy ).\\n(2) 彼はサッカーの試合を見ますか。( soccer games / watch / he / does )?",
       "a": "(1) Lucy speaks English at home.\\n(2) Does he watch soccer games?",
       "al": ["(1)", "(2)"],
       "ly": "stacked"
     }
     \`\`\`

4. **設問形式別の指定ルール**:
   - 空欄は \`[      ]\` または \`(      )\` と表記する。
   - 複数小問がある場合は、\`"al": ["(1)", "(2)", "(3)"]\` のように小問ラベル配列を指定する。
   - 単語テストや1行短答問題は \`"ly": "same-line"\`、英文記述や並べ替えは \`"ly": "stacked"\` を指定する。
   - 絵やイラストを見て答える問題は \`"img": "画像欄"\`（またはイラスト内容）を指定する。
   - リスニング放送原稿がある場合は \`"as": "放送原稿スクリプト"\` を記述する。

---

### 【出力フォーマット（Mini-JSON厳守）】
前置き、挨拶、解説、お礼などは一切出力せず、必ず以下の \`\`\`json コードブロックのみを出力してください。

\`\`\`json
{
  "meta": {
    "tb": "${sampleTb}",
    "gr": "${sampleGr}",
    "tags": ${JSON.stringify(sampleTags)}
  },
  "questions": [
    {
      "tb": "${sampleTb}",
      "gr": "${sampleGr}",
      "g": "英語",
      "t": "大単元名",
      "st": "大問・セクション名",
      "tg": ["タグ1"],
      "d": 1,
      "s": 120,
      "q": "指示文\\n(1) 小問1\\n(2) 小問2",
      "a": "(1) 解答1\\n(2) 解答2",
      "al": ["(1)", "(2)"],
      "ly": "same-line"
    }
  ]
}
\`\`\`
`;
}
